import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import { setTimeout as sleep } from "node:timers/promises";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StreamableHTTPClientTransport } from "@modelcontextprotocol/sdk/client/streamableHttp.js";
import { PDFDocument } from "pdf-lib";
const PORT=45981;
const proc=spawn(process.execPath,["server.js"],{env:{...process.env,PORT:String(PORT)},stdio:"pipe"});
let stderr="";proc.stderr.on("data",c=>stderr+=c);
const base="http://127.0.0.1:"+PORT;
try{
 let ready=false;
 for(let i=0;i<80;i++){
  try{const r=await fetch(base+"/health");if(r.ok){ready=true;break}}catch{}
  await sleep(150);
 }
 assert.equal(ready,true,"Server failed to start: "+stderr);
 const health=await (await fetch(base+"/health")).json();
 assert.equal(health.ok,true);
 const bad=await fetch(base+"/mcp",{method:"POST",headers:{"content-type":"application/json"},body:JSON.stringify(Array(101).fill({jsonrpc:"2.0",id:1,method:"ping"}))});
 assert.equal(bad.status,400,"HTTP batch must be rejected");
 const giant=await fetch(base+"/mcp",{method:"POST",headers:{"content-type":"application/json"},body:"x".repeat(4*1024*1024+10)});
 assert.equal(giant.status,413);
 const origin=await fetch(base+"/mcp",{method:"POST",headers:{"origin":"https://evil.example","content-type":"application/json"},body:"{}"});
 assert.equal(origin.status,403);
 const transport=new StreamableHTTPClientTransport(new URL(base+"/mcp"));
 const client=new Client({name:"justpdfit-test",version:"0.1.0"});
 await client.connect(transport);
 const listing=await client.listTools();
 assert.ok(listing.tools.some(t=>t.name==="merge_pdfs"));
 assert.ok(listing.tools.some(t=>t.name==="create_demo_pdf"));
 assert.equal(listing.tools.length,13);
 assert.ok(listing.tools.some(t=>t.name==="preview_signature_pdf"));
 assert.ok(listing.tools.some(t=>t.name==="propose_signature_placement"));
 assert.ok(listing.tools.some(t=>t.name==="finalize_signature_pdf"));
 assert.deepEqual(listing.tools.find(t=>t.name==="propose_signature_placement")._meta["openai/fileParams"],["file"]);
 const resources=await client.listResources();
 assert.ok(resources.resources.some(r=>r.uri==="ui://justpdfit/editor-v6.html"));
 const widget=await client.readResource({uri:"ui://justpdfit/editor-v6.html"});
 assert.ok(widget.contents.some(c=>c.text?.includes("JustPDFit")));
 const editedDemo=await client.callTool({name:"create_demo_pdf",arguments:{text:"TEST APPROVED"}});
 assert.equal(editedDemo.structuredContent?.filename,"justpdfit-demo-edited.pdf");
 assert.equal((await PDFDocument.load(Buffer.from(editedDemo.structuredContent.base64,"base64"))).getPageCount(),1);
 const demo=await client.callTool({name:"create_demo_pdf",arguments:{}});
 assert.ok(demo.structuredContent?.base64);
 const sample=Buffer.from(demo.structuredContent.base64,"base64");
 assert.equal((await PDFDocument.load(sample)).getPageCount(),1);
 const modified=await client.callTool({name:"annotate_pdf",arguments:{pdf:demo.structuredContent.base64,page:1,text:"Sample approved"}});
 assert.ok(modified.structuredContent?.base64);
 assert.equal((await PDFDocument.load(Buffer.from(modified.structuredContent.base64,"base64"))).getPageCount(),1);
 const pdf=await PDFDocument.create();pdf.addPage([300,400]);
 const base64=Buffer.from(await pdf.save()).toString("base64");
 const result=await client.callTool({name:"inspect_pdf",arguments:{pdf:base64}});
 assert.equal(JSON.parse(result.content[0].text).pages,1);
 const placement=await client.callTool({name:"propose_signature_placement",arguments:{pdf:base64}});
 assert.equal(placement.structuredContent?.pages,1,JSON.stringify(placement).slice(0,1600));
 assert.equal(placement.structuredContent?.requiresConfirmation,true);
 const preview=await client.callTool({name:"preview_signature_pdf",arguments:{pdf:base64,name:"Test Signer",page:1,x:50,y:50}});
 assert.equal(preview.structuredContent?.previewOnly,true);
 assert.ok(preview.structuredContent?.base64);
 const declined=await client.callTool({name:"finalize_signature_pdf",arguments:{pdf:base64,name:"Test Signer",page:1,x:50,y:50,confirmed:false}});
 assert.equal(declined.isError,true);
 const accepted=await client.callTool({name:"finalize_signature_pdf",arguments:{pdf:base64,name:"Test Signer",page:1,x:50,y:50,confirmed:true}});
 assert.ok(accepted.structuredContent?.base64);
 assert.equal((await PDFDocument.load(Buffer.from(accepted.structuredContent.base64,"base64"))).getPageCount(),1);
 await client.close();
 console.log("MCP HTTP smoke tests PASS; 13 tools exposed, placement suggested and signing confirmed, demo generated and annotated");
} finally{
 proc.kill("SIGTERM");
 await sleep(250);
}
